#!/usr/bin/env bash
set -euo pipefail
source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/common.sh"
CLUSTERSET_CONFIG_FILE="${MYSQLK8S_CLUSTERSET_CONFIG:-$SCRIPT_DIR/clusterset.env}"
if [[ -f "$CLUSTERSET_CONFIG_FILE" ]]; then
    set -a
    # shellcheck disable=SC1090
    source "$CLUSTERSET_CONFIG_FILE"
    set +a
fi
export PRIMARY_MYSQL_NAMESPACE="${PRIMARY_MYSQL_NAMESPACE:-$MYSQL_NAMESPACE}"
export PRIMARY_MYSQL_CLUSTER_NAME="${PRIMARY_MYSQL_CLUSTER_NAME:-$MYSQL_CLUSTER_NAME}"
export REPLICA_MYSQL_NAMESPACE="${REPLICA_MYSQL_NAMESPACE:-mysql-secondary}"
export REPLICA_MYSQL_CLUSTER_NAME="${REPLICA_MYSQL_CLUSTER_NAME:-mycluster2}"
export REPLICA_MYSQL_SECRET_NAME="${REPLICA_MYSQL_SECRET_NAME:-mycluster2-root}"
export REPLICA_BASE_SERVER_ID="${REPLICA_BASE_SERVER_ID:-2000}"
export REPLICA_MYSQL_INSTANCES="${REPLICA_MYSQL_INSTANCES:-3}"
export REPLICA_MYSQL_ROUTER_INSTANCES="${REPLICA_MYSQL_ROUTER_INSTANCES:-2}"
export REPLICA_STORAGE_CLASS="${REPLICA_STORAGE_CLASS:-}"
export REPLICA_STORAGE_SIZE="${REPLICA_STORAGE_SIZE:-$MYSQL_STORAGE_SIZE}"
export K8S_CLUSTER_DOMAIN="${K8S_CLUSTER_DOMAIN:-cluster.local}"

#!/usr/bin/env python3
"""Validate configuration and render a Kubernetes manifest using only stdlib."""
import json
import os
import re
import sys


def fail(message):
    sys.exit("ERROR: " + message)


def integer(name, low, high):
    value = os.environ[name]
    if not value.isdigit() or not low <= int(value) <= high:
        fail(f"{name} must be an integer from {low} to {high}.")
    return int(value)


def validate():
    for name in ("OPERATOR_NAMESPACE", "MYSQL_NAMESPACE", "MYSQL_CLUSTER_NAME", "MYSQL_SECRET_NAME"):
        value = os.environ[name]
        # Conservative room for names generated by the operator.
        if len(value) > 40 or not re.fullmatch(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*", value):
            fail(f"{name} must be a lowercase DNS label, start with a letter, and be <=40 characters.")
    if os.environ["OPERATOR_NAMESPACE"] in ("default", "kube-system", "kube-public", "kube-node-lease"):
        fail("Use a dedicated OPERATOR_NAMESPACE.")
    if os.environ["MYSQL_NAMESPACE"] in ("kube-system", "kube-public", "kube-node-lease"):
        fail("Use a workload MYSQL_NAMESPACE.")
    integer("MYSQL_INSTANCES", 1, 9)
    integer("MYSQL_ROUTER_INSTANCES", 1, 9)
    integer("WAIT_TIMEOUT_SECONDS", 1, 86400)
    integer("LOCAL_MYSQL_PORT", 1024, 65535)
    if os.environ["MYSQL_ANTI_AFFINITY"] not in ("required", "preferred"):
        fail("MYSQL_ANTI_AFFINITY must be required or preferred.")
    if not re.fullmatch(r"[1-9][0-9]*(?:Mi|Gi|Ti)", os.environ["MYSQL_STORAGE_SIZE"]):
        fail("MYSQL_STORAGE_SIZE must be a positive Mi/Gi/Ti quantity, such as 10Gi.")
    for name in ("MYSQL_VERSION", "OPERATOR_CHART_VERSION"):
        if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", os.environ[name]):
            fail(f"{name} must be an explicit x.y.z version.")
    if not re.fullmatch(r"v[0-9]+\.[0-9]+\.[0-9]+", os.environ["HELM_VERSION"]):
        fail("HELM_VERSION must be an explicit vx.y.z version.")


def storage():
    classes = json.load(sys.stdin)["items"]
    requested = os.environ["STORAGE_CLASS"]
    if requested:
        if requested not in [s["metadata"]["name"] for s in classes]:
            fail(f"StorageClass {requested!r} does not exist.")
        print(requested)
        return
    defaults = [s["metadata"]["name"] for s in classes if any(
        s["metadata"].get("annotations", {}).get(key) == "true" for key in (
            "storageclass.kubernetes.io/is-default-class",
            "storageclass.beta.kubernetes.io/is-default-class"))]
    if len(defaults) != 1:
        fail("Set STORAGE_CLASS in config.env, or configure exactly one default StorageClass with a working CSI provisioner.")
    print(defaults[0])


def nodes():
    eligible = []
    for node in json.load(sys.stdin)["items"]:
        spec = node.get("spec", {})
        labels = node["metadata"].get("labels", {})
        ready = any(c["type"] == "Ready" and c["status"] == "True"
                    for c in node.get("status", {}).get("conditions", []))
        blocked = spec.get("unschedulable", False) or any(
            t["effect"] in ("NoSchedule", "NoExecute") for t in spec.get("taints", []))
        if ready and not blocked and labels.get("kubernetes.io/os") == "linux" and labels.get("kubernetes.io/arch") in ("amd64", "arm64"):
            eligible.append(node["metadata"]["name"])
    required = int(os.environ["MYSQL_INSTANCES"]) if os.environ["MYSQL_ANTI_AFFINITY"] == "required" else 1
    if len(eligible) < required:
        fail(f"Need {required} Ready, uncordoned Linux amd64/arm64 nodes without NoSchedule/NoExecute taints; found {len(eligible)}. For a lab, set MYSQL_INSTANCES=1 or MYSQL_ANTI_AFFINITY=preferred.")
    print("Eligible worker nodes: " + ", ".join(eligible))


def build_manifest():
    name = os.environ["MYSQL_CLUSTER_NAME"]
    term = {"labelSelector": {"matchLabels": {
        "mysql.oracle.com/cluster": name, "component": "mysqld"}},
        "topologyKey": "kubernetes.io/hostname"}
    affinity = ({"requiredDuringSchedulingIgnoredDuringExecution": [term]}
                if os.environ["MYSQL_ANTI_AFFINITY"] == "required" else
                {"preferredDuringSchedulingIgnoredDuringExecution": [{"weight": 100, "podAffinityTerm": term}]})
    document = {
        "apiVersion": "mysql.oracle.com/v2", "kind": "InnoDBCluster",
        "metadata": {"name": name, "namespace": os.environ["MYSQL_NAMESPACE"]},
        "spec": {
            "secretName": os.environ["MYSQL_SECRET_NAME"],
            "edition": "community", "version": os.environ["MYSQL_VERSION"],
            "tlsUseSelfSigned": True, "instances": int(os.environ["MYSQL_INSTANCES"]),
            "service": {"type": "ClusterIP"},
            "router": {"instances": int(os.environ["MYSQL_ROUTER_INSTANCES"]),
                       "version": os.environ["MYSQL_VERSION"],
                       "podSpec": {"containers": [{"name": "router", "resources": {
                           "requests": {"cpu": "100m", "memory": "128Mi"},
                           "limits": {"memory": "256Mi"}}}]}},
            "datadirVolumeClaimTemplate": {
                "accessModes": ["ReadWriteOnce"], "storageClassName": os.environ["STORAGE_CLASS"],
                "resources": {"requests": {"storage": os.environ["MYSQL_STORAGE_SIZE"]}}},
            "mycnf": "[mysqld]\ninnodb_buffer_pool_size=512M\n",
            "podSpec": {
                "nodeSelector": {"kubernetes.io/os": "linux"},
                "affinity": {"podAntiAffinity": affinity},
                "containers": [
                    {"name": "mysql", "resources": {
                        "requests": {"cpu": "500m", "memory": "1Gi"},
                        "limits": {"memory": "2Gi"}}},
                    {"name": "sidecar", "resources": {
                        "requests": {"cpu": "100m", "memory": "128Mi"},
                        "limits": {"memory": "512Mi"}}}]}}}
    return document


def manifest():
    json.dump(build_manifest(), sys.stdout, indent=2)
    print()


if __name__ == "__main__":
    validate()
    {"validate": lambda: None, "storage": storage, "nodes": nodes, "manifest": manifest}[sys.argv[1]]()
